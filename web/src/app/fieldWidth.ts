/** How wide every field and picker in a card is, in the spacing scale's steps
 * (20rem): its control keeps it from a phone's column up, and fills a
 * narrower one. */
export const FIELD_WIDTH = 80;

/** A field as wide as two fields standing side by side in a row, with the
 * row's 16 px (4 steps) between them, such as an address over a pair. */
export const PAIR_WIDTH = 2 * FIELD_WIDTH + 4;
